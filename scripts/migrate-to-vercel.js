require("dotenv").config();

const fs = require("fs");
const path = require("path");
const Database = require("better-sqlite3");
const { neon } = require("@neondatabase/serverless");
const { put } = require("@vercel/blob");

const root = path.join(__dirname, "..");
const databaseUrl = process.env.DATABASE_URL;

if (!databaseUrl || !process.env.BLOB_READ_WRITE_TOKEN) {
  throw new Error("Set DATABASE_URL and BLOB_READ_WRITE_TOKEN before migration.");
}

const sourcePath = path.join(root, "data", "skphotography.db");
if (!fs.existsSync(sourcePath)) {
  throw new Error(`Local SQLite database not found: ${sourcePath}`);
}

const source = new Database(sourcePath, { readonly: true });
const sql = neon(databaseUrl);

async function migrate() {
  const schema = [
    `CREATE TABLE IF NOT EXISTS admins (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL
    )`,
    "CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL)",
    `CREATE TABLE IF NOT EXISTS photos (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      category TEXT NOT NULL,
      filename TEXT NOT NULL UNIQUE,
      url TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`,
    `CREATE TABLE IF NOT EXISTS bookings (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      phone TEXT NOT NULL,
      email TEXT NOT NULL DEFAULT '',
      service TEXT NOT NULL,
      event_date TEXT NOT NULL DEFAULT '',
      message TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'New',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`,
    `CREATE TABLE IF NOT EXISTS password_reset_challenges (
      id INTEGER PRIMARY KEY CHECK (id = 1),
      code_hash TEXT NOT NULL,
      expires_at TIMESTAMPTZ NOT NULL,
      attempts INTEGER NOT NULL DEFAULT 0
    )`
  ];
  for (const statement of schema) await sql.query(statement);

  const admins = source.prepare(
    "SELECT id, username, password_hash FROM admins"
  ).all();
  for (const admin of admins) {
    await sql.query(
      `INSERT INTO admins (id, username, password_hash) VALUES ($1, $2, $3)
       ON CONFLICT (username) DO UPDATE SET password_hash = EXCLUDED.password_hash`,
      [admin.id, admin.username, admin.password_hash]
    );
  }

  const settings = source.prepare("SELECT key, value FROM settings").all();
  for (const setting of settings) {
    await sql.query(
      `INSERT INTO settings (key, value) VALUES ($1, $2)
       ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`,
      [setting.key, setting.value]
    );
  }

  const localPhotos = source.prepare(
    "SELECT id, title, category, filename, created_at FROM photos ORDER BY id"
  ).all();
  for (const photo of localPhotos) {
    const localFile = path.join(root, "uploads", path.basename(photo.filename));
    if (!fs.existsSync(localFile)) {
      throw new Error(`Photo file is missing; cannot migrate: ${localFile}`);
    }

    const extension = path.extname(photo.filename).toLowerCase();
    const contentType = {
      ".jpg": "image/jpeg",
      ".jpeg": "image/jpeg",
      ".png": "image/png",
      ".webp": "image/webp",
      ".gif": "image/gif"
    }[extension];
    if (!contentType) {
      throw new Error(`Unsupported photo type for migration: ${photo.filename}`);
    }
    const blob = await put(
      `portfolio/${photo.id}-${path.basename(photo.filename)}`,
      fs.readFileSync(localFile),
      { access: "public", contentType }
    );
    await sql.query(
      `INSERT INTO photos (id, title, category, filename, url, created_at)
       VALUES ($1, $2, $3, $4, $5, $6)
       ON CONFLICT (id) DO UPDATE SET
         title = EXCLUDED.title,
         category = EXCLUDED.category,
         filename = EXCLUDED.filename,
         url = EXCLUDED.url`,
      [photo.id, photo.title, photo.category, path.basename(photo.filename), blob.url, photo.created_at]
    );
  }

  const bookings = source.prepare(`
    SELECT id, name, phone, email, service, event_date,
           message, status, created_at
    FROM bookings ORDER BY id
  `).all();
  for (const booking of bookings) {
    await sql.query(
      `INSERT INTO bookings
        (id, name, phone, email, service, event_date, message, status, created_at)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
       ON CONFLICT (id) DO UPDATE SET
         name = EXCLUDED.name,
         phone = EXCLUDED.phone,
         email = EXCLUDED.email,
         service = EXCLUDED.service,
         event_date = EXCLUDED.event_date,
         message = EXCLUDED.message,
         status = EXCLUDED.status`,
      [
        booking.id, booking.name, booking.phone, booking.email, booking.service,
        booking.event_date, booking.message, booking.status, booking.created_at
      ]
    );
  }

  for (const table of ["admins", "photos", "bookings"]) {
    await sql.query(`
      SELECT setval(
        pg_get_serial_sequence('${table}', 'id'),
        COALESCE((SELECT MAX(id) FROM ${table}), 1),
        EXISTS (SELECT 1 FROM ${table})
      )
    `);
  }

  console.log(`Migrated ${admins.length} admins, ${settings.length} settings, ${localPhotos.length} photos, and ${bookings.length} bookings.`);
}

migrate()
  .catch(error => {
    console.error("Migration failed:", error);
    process.exitCode = 1;
  })
  .finally(() => source.close());
